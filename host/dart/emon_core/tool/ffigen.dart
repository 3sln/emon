// Generates lib/src/bindings.g.dart from the C headers of host/c/include (emon.h, emon_adapter.h).
// Run from anywhere: `bb dart --bindings` (or `dart run tool/ffigen.dart` inside host/dart/emon_core).
// The bindings are COMMITTED; `bb dart --bindings --check` fails when they differ from what the headers give.
import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main(List<String> args) async {
  final packageRoot = Platform.script.resolve('../');
  final headers = packageRoot.resolve('../../c/include/');
  final out = args.isNotEmpty ? Uri.file(args.first) : packageRoot.resolve('lib/src/bindings.g.dart');
  bool ours(String name) => name.startsWith('emon_') || name.startsWith('EMON_');
  final generator = FfiGenerator(
    output: Output(
      dart: DartOutput(path: out),
      style: const NativeExternalBindings(assetId: 'package:emon_core/src/bindings.g.dart'),
      commentType: const CommentType(CommentStyle.doxygen, CommentLength.full),
      preamble: '// GENERATED by tool/ffigen.dart from host/c/include/emon.h and emon_adapter.h. Do not edit.\n'
          '// ignore_for_file: type=lint, unused_field, unused_element\n',
    ),
    input: Input(
      entryPoints: [headers.resolve('emon.h')],
      include: (u) => u.path.endsWith('/emon.h') || u.path.endsWith('/emon_adapter.h'),
    ),
    visitors: [
      Visitor(func: (n) => n.isIncluded = ours(n.originalName)),
      Visitor(struct: (n) => n.isIncluded = ours(n.originalName)),
      Visitor(typealias: (n) => n.isIncluded = ours(n.originalName) ? TypealiasInclude.ifUsed : TypealiasInclude.never),
      Visitor(macroConstant: (n) => n.isIncluded = ours(n.originalName)),
    ],
  );
  await generator.generate();
}
