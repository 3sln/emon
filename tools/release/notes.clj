#!/usr/bin/env bb
;; Release notes (P11.9, D547): the DEVLOG decisions and the commits since the previous tag, as the Markdown body of the DRAFT GitHub release.
;;
;;   bb release-notes [--since TAG|SHA] [--until REF] [--version X.Y.Z] [--out FILE] [--max-decisions N] [--max-commits N]
;;   bb release-notes --self-test
;;
;; --since   the base (default: the newest v* tag reachable from --until; none yet, the first commit, and the notes say it is the first release)
;; --until   the commit being released (default HEAD)
;; --version the version in the title and the install table (default: version.edn of the working tree)
;; --out     write the notes there (default: stdout)
;; The notes are a DRAFT for the maintainer to edit before publishing: decisions are the D### headings of DEVLOG.md that are new since the base (by id),
;; roadmap items are the `- [x] P..` lines ticked since the base, commits are `git log --no-merges`. Both lists are capped (the first release would
;; otherwise list the whole project) and say how many were left out. Nothing is written to the repository and nothing is published.
(require '[clojure.edn :as edn]
         '[clojure.string :as str]
         '[release.lib :as rl])

;; ---------------------------------------------------------------------------------------------------- pure parts
(defn decisions
  "The D### headings of a DEVLOG text, in file order: [{:id \"D524\" :title \"...\"}]."
  [text]
  (vec (for [[_ id title] (re-seq #"(?m)^### (D\d+) — (.+?)\s*$" (or text ""))]
         {:id id :title title})))

(defn new-decisions "Decisions of `new-text` whose id is not in `old-text`." [old-text new-text]
  (let [old (set (map :id (decisions old-text)))]
    (vec (remove #(old (:id %)) (decisions new-text)))))

(defn ticked
  "The roadmap items ticked `[x]` in a DEVLOG text, in file order: [[\"P11.1\" \"first line\"] ...]."
  [text]
  (vec (for [[_ id title] (re-seq #"(?m)^\s*- \[x\] (P\d+\.[0-9A-Za-z]+) — (.+?)\s*$" (or text ""))] [id title])))

(defn newly-ticked [old-text new-text]
  (let [old (set (map first (ticked old-text)))]
    (vec (for [[id t] (ticked new-text) :when (not (old id))] {:id id :title t}))))

(defn- capped
  "Keep the LAST n (the newest: DEVLOG and the roadmap grow at the end) and count the ones left out."
  [items n]
  (if (and n (> (count items) n)) [(take-last n items) (- (count items) n)] [items 0]))

(defn- first-sentence [s] (let [s (str/replace s #"`" "'")] (if (> (count s) 160) (str (subs s 0 157) "...") s)))

(defn render
  "The notes. m: {:version :since (label) :first? :decisions :items :commits :max-decisions :max-commits}."
  [{:keys [version since first? decisions items commits max-decisions max-commits]}]
  (let [[ds dmore] (capped decisions max-decisions)
        [is imore] (capped items max-decisions)
        ;; commits are newest first, so the cap keeps the head, not the tail
        [cs cmore] (if (and max-commits (> (count commits) max-commits)) [(take max-commits commits) (- (count commits) max-commits)] [commits 0])
        tag (str "v" version)
        sb (StringBuilder.)
        line (fn [& xs] (.append sb (apply str xs)) (.append sb "\n"))]
    (line "# emon " tag)
    (line)
    (line (if first? "The first release of emon." (str "Changes since `" since "`.")) " This is a DRAFT generated by `bb release-notes` from DEVLOG.md and the git log; edit it before publishing.")
    (line)
    (line "## Install")
    (line)
    (line "| Where | Package |")
    (line "|---|---|")
    (line "| crates.io | `emon` " version " |")
    (line "| npm | `@3sln/emon@" version "` |")
    (line "| NuGet | `Emon` " version " |")
    (line "| Maven Central | `com.3sln:emon:" version "` |")
    (line "| Go | `go get github.com/3sln/emon/go@v" version "` (tag `go/v" version "`) |")
    (line "| Command line | `emon-" version "-<triple>.tar.gz` (`.zip` on Windows), attached below, with `.sha256` |")
    (line "| C library | `emon-c-" version "-<triple>.tar.gz`, attached below |")
    (line "| babashka pod | `emon-pod-" version "-<triple>.tar.gz`, attached below |")
    (line)
    (when (seq items)
      (line "## Roadmap items completed (" (count items) ")")
      (line)
      (when (pos? imore) (line "- ... " imore " earlier items not listed (see DEVLOG.md)"))
      (doseq [{:keys [id title]} is] (line "- " id " — " (first-sentence title)))
      (line))
    (line "## Decisions recorded (" (count decisions) ")")
    (line)
    (if (empty? ds)
      (line "None.")
      (doseq [{:keys [id title]} ds] (line "- " id " — " (first-sentence title))))
    (when (pos? dmore) (line "- ... " dmore " earlier decisions not listed (see DEVLOG.md)"))
    (line)
    (line "## Commits (" (count commits) ")")
    (line)
    (if (empty? cs)
      (line "None.")
      (doseq [{:keys [sha subject]} cs] (line "- `" sha "` " subject)))
    (when (pos? cmore) (line "- ... and " cmore " more (`git log`)"))
    (str sb)))

;; ---------------------------------------------------------------------------------------------------- git
(defn- show-devlog [ref]
  (let [r (rl/git "show" (str ref ":DEVLOG.md"))] (if (zero? (:exit r)) (:out r) "")))

(defn- newest-tag
  "The newest v* tag before `until`: if `until` is itself tagged (the release being noted), that tag is not the base, so the search starts at its parent."
  [until]
  (let [tagged? (zero? (:exit (rl/git "describe" "--tags" "--exact-match" "--match" "v[0-9]*" until)))
        r (rl/git "describe" "--tags" "--abbrev=0" "--match" "v[0-9]*" (if tagged? (str until "^") until))]
    (when (zero? (:exit r)) (str/trim (:out r)))))

(defn- root-commit [until] (str/trim (last (str/split-lines (:out (rl/git! "rev-list" "--max-parents=0" until))))))

(defn- commits [since until]
  (let [r (rl/git! "log" "--no-merges" "--format=%h%x09%s" (if since (str since ".." until) until))]
    (vec (for [l (str/split-lines (:out r)) :when (not (str/blank? l))
               :let [[sha s] (str/split l #"\t" 2)]]
           {:sha sha :subject s}))))

(defn build [{:keys [since until version max-decisions max-commits]}]
  (let [until (or until "HEAD")
        base (or since (newest-tag until))
        first? (nil? base)
        base* (or base (root-commit until))
        old (if first? "" (show-devlog base*))
        new (show-devlog until)
        version (or version (:version (edn/read-string (slurp "version.edn"))))]
    (render {:version version :since (or base "") :first? first?
             :decisions (if first? (decisions new) (new-decisions old new))
             :items (if first? (vec (for [[id t] (ticked new)] {:id id :title t})) (newly-ticked old new))
             :commits (commits (when-not first? base*) until)
             :max-decisions max-decisions :max-commits max-commits})))

;; ---------------------------------------------------------------------------------------------------- self-test
(def ^:private old-log "## Phase\n- [x] P1.1 — one\n- [ ] P1.2 — two\n\n### D001 — First (P1)\nx\n### D002 — Second\n")
(def ^:private new-log "## Phase\n- [x] P1.1 — one\n- [x] P1.2 — two done\n- [ ] P1.3 — three\n\n### D001 — First (P1)\nx\n### D002 — Second\n### D003 — Third `thing` (P1.2; D001)\n")

(defn self-test []
  (let [[t! done!] (rl/selftest-runner)]
    (t! "decisions are read in file order" (= ["D001" "D002" "D003"] (map :id (decisions new-log))))
    (t! "a decision's title is the heading text" (= "First (P1)" (:title (first (decisions old-log)))))
    (t! "new decisions are those whose id is not in the old log" (= ["D003"] (map :id (new-decisions old-log new-log))))
    (t! "no old log: every decision is new" (= 3 (count (new-decisions "" new-log))))
    (t! "a body line that looks like a heading with four hashes is not one" (empty? (decisions "#### D009 — nope\n")))
    (t! "ticked items are only the [x] ones" (= ["P1.1" "P1.2"] (map first (ticked new-log))))
    (t! "newly ticked: P1.2 only" (= ["P1.2"] (map :id (newly-ticked old-log new-log))))
    (let [m {:version "1.2.3" :since "v1.2.2" :first? false :decisions (decisions new-log) :items (newly-ticked old-log new-log)
             :commits [{:sha "abc1234" :subject "fix: a thing"} {:sha "def5678" :subject "feat: another"}]}
          out (render m)]
      (t! "title carries the tag" (str/starts-with? out "# emon v1.2.3\n"))
      (t! "base is named" (str/includes? out "Changes since `v1.2.2`."))
      (t! "install table names every registry"
          (every? #(str/includes? out %) ["crates.io" "`@3sln/emon@1.2.3`" "`com.3sln:emon:1.2.3`" "github.com/3sln/emon/go@v1.2.3" "emon-pod-1.2.3"]))
      (t! "a decision line" (str/includes? out "- D003 — Third 'thing' (P1.2; D001)"))
      (t! "a commit line" (str/includes? out "- `abc1234` fix: a thing"))
      (t! "an item line" (str/includes? out "- P1.2 — two done"))
      (t! "first release wording" (str/includes? (render (assoc m :first? true)) "The first release of emon."))
      (let [capped-out (render (assoc m :max-decisions 1 :max-commits 1))]
        (t! "caps say how many were left out" (and (str/includes? capped-out "... 2 earlier decisions not listed") (str/includes? capped-out "... and 1 more (`git log`)")))
        (t! "decisions are capped to the NEWEST, commits to the newest (git log order)"
            (and (str/includes? capped-out "- D003") (not (str/includes? capped-out "- D001")) (str/includes? capped-out "`abc1234`") (not (str/includes? capped-out "`def5678`")))))
      (t! "no decisions: None." (str/includes? (render (assoc m :decisions [] :items [])) "None.")))
    (let [v (rl/tag->version "v0.1.0")]
      (t! "tag->version" (and (= "0.1.0" v) (nil? (rl/tag->version "0.1")) (= "1.2.3-rc.1" (rl/tag->version "1.2.3-rc.1")))))
    (done!)))

;; ---------------------------------------------------------------------------------------------------- main
(defn -main [args]
  (let [opts (loop [as args o {}]
               (if-let [a (first as)]
                 (case a
                   "--since" (recur (nnext as) (assoc o :since (second as)))
                   "--until" (recur (nnext as) (assoc o :until (second as)))
                   "--version" (recur (nnext as) (assoc o :version (rl/tag->version (second as))))
                   "--out" (recur (nnext as) (assoc o :out (second as)))
                   "--max-decisions" (recur (nnext as) (assoc o :max-decisions (parse-long (second as))))
                   "--max-commits" (recur (nnext as) (assoc o :max-commits (parse-long (second as))))
                   (rl/die 2 "usage: bb release-notes [--since TAG] [--until REF] [--version X.Y.Z] [--out FILE] [--max-decisions N] [--max-commits N] | --self-test"))
                 o))
        opts (merge {:max-decisions 80 :max-commits 100} opts)
        notes (build opts)]
    (if-let [f (:out opts)]
      (do (spit f notes) (println (str "wrote " f " (" (count (str/split-lines notes)) " lines)")))
      (print notes))))

(when (= *file* (System/getProperty "babashka.file"))
  (if (= ["--self-test"] (vec *command-line-args*))
    (self-test)
    (-main *command-line-args*)))
