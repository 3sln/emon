#!/usr/bin/env bb
;; Generate kin/pdfsnames.kin: the PDF names the structure-tree reader (P3.7, D148) compares
;; against by BYTES, and the standard structure types it resolves a role to.
;;
;;     bb tools/pdfsnames.clj            write kin/pdfsnames.kin
;;     bb tools/pdfsnames.clj --check    fail if the committed file is stale
;;
;; Like `tools/pdfxnames.clj` (D120) and for its reason: kin has no string values and the object
;; arena's table of interned names is full and shared. A separate generated module keeps P3.7's names
;; out of the other readers' tables (two agents appending to one table is a merge conflict).
;; The id of a name is its position; appending is safe, nothing else is. Babashka (D094).
(require '[clojure.string :as str])

;; Keys and values the tree reader meets.
(def names
  ["K" "S" "P" "Pg" "Obj" "Stm" "StmOwn" "MCID" "Type" "StructElem" "MCR" "OBJR"
   "StructTreeRoot" "RoleMap" "ClassMap" "ParentTree" "ParentTreeNextKey" "IDTree" "ID" "C" "A" "O"
   "Lang" "Alt" "ActualText" "E" "T" "NS" "Nums" "Kids" "Names" "Limits" "MarkInfo" "Marked"
   "Suspects" "UserProperties" "StructParent" "StructParents" "Subtype" "Link" "Widget" "Form" "Image"
   "Scope" "Headers" "RowSpan" "ColSpan" "Summary" "ListNumbering" "Row" "Column" "Both"
   "None" "Unordered" "Ordered" "Disc" "Circle" "Square" "Decimal" "UpperRoman" "LowerRoman"
   "UpperAlpha" "LowerAlpha" "Layout" "List" "PrintField" "Table" "Hyperlink" "Root"])

;; The standard structure types (ISO 32000-1 14.8.4, 32000-2 14.8.4) and `Artifact`, which producers write as a
;; structure type.  The CODE of a role is its position + 1 (0 is "none"); `Hn` stands for H1, H2, ... and is
;; matched by its numerals, never by this spelling.  CODES ARE FOREVER: append only.
(def roles
  ["Document" "DocumentFragment" "Part" "Art" "Sect" "Div" "Aside" "NonStruct" "Private" "BlockQuote"
   "Caption" "TOC" "TOCI" "Index" "P" "H" "Hn" "Title" "L" "LI" "Lbl" "LBody" "Span" "Quote" "Note" "FENote"
   "Reference" "BibEntry" "Code" "Link" "Annot" "Em" "Strong" "Sub" "Ruby" "RB" "RT" "RP" "Warichu" "WT" "WP"
   "Table" "TR" "TH" "TD" "THead" "TBody" "TFoot" "Figure" "Formula" "Form" "Artifact"])

(defn sym [x]
  (-> x
      (str/replace #"(?<=[a-z0-9])(?=[A-Z])" "-")
      (str/replace #"(?<=[A-Z])(?=[A-Z][a-z])" "-")
      str/lower-case))

(defn spans [xs]
  (loop [o 0 xs xs acc []]
    (if (seq xs)
      (recur (+ o (count (first xs))) (rest xs) (conj acc o (count (first xs))))
      acc)))

(defn rows [xs w] (str/join "\n         " (map #(str/join " " %) (partition-all w xs))))

(defn render []
  (let [nsyms (mapv #(str "sn-" (sym %)) names)
        rsyms (mapv #(str "sr-" (sym %)) roles)
        _ (assert (= (count nsyms) (count (set nsyms))) (str "duplicate name symbol " (frequencies nsyms)))
        _ (assert (= (count rsyms) (count (set rsyms))) (str "duplicate role symbol " (frequencies rsyms)))
        nchars (vec (mapcat #(map int %) names))
        rchars (vec (mapcat #(map int %) roles))]
    (str ";; GENERATED by tools/pdfsnames.clj -- do not edit.\n;;\n"
         ";; The " (count names) " PDF names and the " (count roles) " structure types the tag-tree reader (P3.7, D148)\n"
         ";; compares by BYTES. The id of a name is its position; appending is safe, nothing else is.\n"
         ";; A role's code is its position + 1: `sr-` below is that code, `sr-emit-name` its spelling.\n"
         "(ns emon.pdfsnames\n  (:require [emon.lang :refer [I32 defenum]]\n"
         "            [kin.lang :refer [defdata]]))\n\n"
         "(defenum ^:pub sn\n  ["
         (str/join "\n   " (map-indexed (fn [i [s n]] (str "[" s " " i " \"" n "\"]")) (map vector nsyms names)))
         "])\n\n"
         ";; the bytes of every name, back to back\n"
         "(defdata ^:pub sn-chars\n  :emitter kin.lang/flat-array\n  :data [" (rows nchars 16) "]\n"
         "  :accessors {^I32 sn-chars-at [^I32 ignored ^I32 i]})\n\n"
         ";; start offset into sn-chars, length\n"
         "(defdata ^:pub sn-span\n  :emitter kin.lang/flat-array\n  :stride 2\n  :data [" (rows (spans names) 16) "]\n"
         "  :accessors {^I32 sn-span-count [^I32 ignored]\n"
         "              ^I32 sn-span-at [^I32 ignored ^I32 row ^I32 field]})\n\n"
         "(defenum ^:pub sr\n  ["
         (str/join "\n   " (map-indexed (fn [i [s n]] (str "[" s " " (inc i) " \"" n "\"]")) (map vector rsyms roles)))
         "])\n\n"
         ";; the bytes of every role, back to back\n"
         "(defdata ^:pub sr-chars\n  :emitter kin.lang/flat-array\n  :data [" (rows rchars 16) "]\n"
         "  :accessors {^I32 sr-chars-at [^I32 ignored ^I32 i]})\n\n"
         ";; start offset into sr-chars, length: row i is the role of code i + 1\n"
         "(defdata ^:pub sr-offs\n  :emitter kin.lang/flat-array\n  :stride 2\n  :data [" (rows (spans roles) 16) "]\n"
         "  :accessors {^I32 sr-offs-count [^I32 ignored]\n"
         "              ^I32 sr-offs-at [^I32 ignored ^I32 row ^I32 field]})\n")))

(let [path (str (-> *file* java.io.File. .getCanonicalFile .getParentFile .getParent) "/kin/pdfsnames.kin")
      text (render)]
  (if (some #{"--check"} *command-line-args*)
    (if (and (.exists (java.io.File. path)) (= text (slurp path)))
      (println "  ok   kin/pdfsnames.kin is current")
      (do (println "  FAIL kin/pdfsnames.kin is stale; run bb tools/pdfsnames.clj") (System/exit 1)))
    (spit path text)))
