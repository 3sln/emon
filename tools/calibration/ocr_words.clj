#!/usr/bin/env bb
;; D883: derive the PP word map from the frozen disjoint fit population.
(require '[cheshire.core :as json] '[clojure.string :as str])
(def fit-source (json/parse-string (slurp "tools/ppocr/calibration.json") true))
(def blocks
  (reduce (fn [out {:keys [bin n correct]}]
            (loop [xs (conj out {:lo (* bin 100) :hi (* bin 100) :n n :correct correct})]
              (if (< (count xs) 2) xs
                (let [b (peek xs) a (peek (pop xs))
                      ;; Empty bins retain their conservative zero estimate.
                      pa (if (pos? (:n a)) (/ (:correct a) (:n a)) 0)
                      pb (if (pos? (:n b)) (/ (:correct b) (:n b)) 0)]
                  (if (<= pa pb) xs
                    (recur (conj (pop (pop xs))
                                 {:lo (:lo a) :hi (:hi b) :n (+ (:n a) (:n b))
                                  :correct (+ (:correct a) (:correct b))})))))))
          [] (get-in fit-source [:fit :bins])))
(def rows
  (mapv (fn [{:keys [lo n correct]}]
          [2 0 1 lo (if (pos? n) (quot (+ (* correct 1000) (quot n 2)) n) 0)]) blocks))
(def content
  (str ";; GENERATED by bb tools/calibration/ocr_words.clj --write.\n"
       ";; Frozen D845 fit observations, weighted isotonic repair (D883 ruling 6).\n"
       ";; [engine calibration-class confidence-kind raw-lo probability], per mille.\n"
       "(ns emon.ocalibdata\n  (:require [emon.lang :refer [I32]]\n            [kin.lang :refer [defdata]]))\n\n"
       "(defdata ^:pub ocd-rows\n  :emitter kin.lang/flat-array\n  :stride 5\n  :data [" (str/join "\n         " (map #(str/join " " %) rows)) "]\n"
       "  :accessors {^I32 ocd-count [^I32 ignored]\n              ^I32 ocd-at [^I32 ignored ^I32 row ^I32 col]})\n"))
(case (first *command-line-args*)
  "--write" (spit "kin/ocalibdata.kin" content)
  (assert (= content (slurp "kin/ocalibdata.kin")) "OCR word calibration drift; regenerate with --write"))
(assert (= [600 422] (subvec (first (filter #(= (nth % 3) 600) rows)) 3)))
(println "OCR word map: weighted isotonic fit verified; bins 6/7 pool 57 correct of 135")

;; Retain an aggregate reliability artifact; no source text or images enter it.
(require '[babashka.fs :as fs] '[calibration.calibration :as calibration])
(defn probability [raw-bin]
  (nth (last (filter #(<= (nth % 3) (* raw-bin 100)) rows)) 4))
(def observations
  (vec (mapcat (fn [split]
                 (mapcat (fn [{:keys [bin n correct]}]
                           (concat (repeat correct {:run (name split) :cat "receipt" :id (str (name split) "-" bin)
                                                    :kind "word" :class "ocr" :conf (probability bin) :y 1000})
                                   (repeat (- n correct) {:run (name split) :cat "receipt" :id (str (name split) "-" bin)
                                                         :kind "word" :class "ocr" :conf (probability bin) :y 0})))
                         (get-in fit-source [split :bins]))) [:fit :validation])))
(def word-out "test/calibration/engines/2")
(def word-artifacts
  {"word-fit.edn" (str (pr-str {:source "tools/ppocr/calibration.json" :method :weighted-pava
                                  :model-pins-sha256 (:model_pins_sha256 fit-source)
                                  :fit-words (get-in fit-source [:fit :words])
                                  :validation-words (get-in fit-source [:validation :words])
                                  :rows rows :pooled-bin {:correct 57 :n 135 :probability 422}}) "\n")
   "word-reliability.csv" ((ns-resolve 'calibration.calibration 'reliability-csv) observations)
   "word-summary.csv" ((ns-resolve 'calibration.calibration 'summary-csv) observations nil)
   "word-reliability.svg" ((ns-resolve 'calibration.calibration 'svg) observations "PP word calibration, weighted isotonic D845 fit")})
(doseq [[name value] word-artifacts]
  (let [path (str word-out "/" name)]
    (if (= ["--write"] *command-line-args*)
      (do (fs/create-dirs word-out) (spit path value))
      (assert (= value (slurp path)) (str "OCR word reliability artifact drift: " path)))))
