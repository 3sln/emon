import assert from 'node:assert/strict';
import fs from 'node:fs';
import { Wasm } from '../../host/js/src/wasm.js';
import { ppocrPort } from '../../host/js/src/ppocr.js';
import { ocrRequest } from '../../host/js/src/ocr.js';
const source = fs.readFileSync('.cache/emon-wasm-ppocr/target/wasm32-unknown-unknown/release/emon.wasm');
const module = await WebAssembly.compile(source);
assert.deepEqual(WebAssembly.Module.imports(module), [{ module: 'ppocr', name: 'valid_word', kind: 'function' }]);
const w = await Wasm.instantiate(module);
const policy = 'ppocr5-en-0420cd75efc786ba37d1e028a4c9396d2f17a3b4264880f1296a7f186faced7f';
const plain = [11, w.kind.ocr, 2, 1, 3, 0, 0, 0, 0, 0, 1701734144];
const tagged = plain.concat([-3100, 1, policy.length], Array.from(policy, c => c.codePointAt(0)));
tagged[0] = tagged.length;
const check = rec => w.withBytes(new Uint8Array(Int32Array.from(rec).buffer), (p, n) => w.x.emon_pp_check(p, n, 0, 0));
assert.equal(check(plain), 0);
assert.equal(check(tagged), 1);
const wrong = tagged.slice(); wrong[wrong.length - 1] ^= 1;
assert.equal(check(wrong), -1);
const spanish = tagged.slice(); spanish[10] = 1936744704;
assert.equal(check(spanish), 2);
const best = tagged.slice(); best[5] = 4;
assert.equal(check(best), 2);
const request = ocrRequest(plain, () => new Uint8Array(), w);
assert.equal(Object.hasOwn(request, 'record'), false);
assert.deepEqual(request.langs, ['eng']);
const ppRequest = ocrRequest(tagged, () => new Uint8Array(), w);
assert.deepEqual(ppRequest.langs, ['eng']);
assert.deepEqual(Array.from(ppRequest.record), tagged);
const view = [13, w.kind.ocr, 2, 2147483647, 3, 0, 0, 0, 0, 0, -3100, 123, 1701734144];
assert.equal(Object.hasOwn(ocrRequest(view, () => new Uint8Array(), w), 'record'), false);
assert.equal(w.x.emon_pp_resume(0, 0, 0), -1);
let loaded = 0, incumbentCalls = 0;
const incumbent = async () => { incumbentCalls++; return { words: [] }; };
const port = ppocrPort({ incumbent, loadOrt: () => { loaded++; throw new Error('must remain lazy'); } });
await port(request);
await port.terminate();
assert.equal(loaded, 0);
assert.equal(incumbentCalls, 1);
console.log('Optional wasm imports only the direct wasm dictionary function; identity/model refusals and option-off lazy delegation passed.');
