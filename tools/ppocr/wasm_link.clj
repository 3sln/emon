#!/usr/bin/env bb
;; Compile tiny memory-framing shims, never an OCR algorithm. WABT is dev-only.
(require '[babashka.fs :as fs] '[babashka.process :refer [process]] '[clojure.string :as str])
(def root ".cache/ppocr-web-link")
(fs/create-dirs root)
;; WABT 1.0.39 leaves Relaxed SIMD disabled unless explicitly enabled. This
;; proves the pinned artifacts, rather than relying on the runtime feature flag.
(doseq [binary ["host/js/node_modules/onnxruntime-web/dist/ort-wasm-simd-threaded.wasm"
                "host/js/node_modules/tesseract.js-core/tesseract-core-simd-lstm.wasm"]]
  (assert (zero? (:exit @(process ["node" "host/js/node_modules/wabt/bin/wasm-validate" "--enable-threads" binary]
                                  {:inherit true :shutdown nil}))) "runtime must validate without Relaxed SIMD"))
(def parts
  (for [[name export] [["trampoline" "trampolineBytes"] ["dictionary" "dictionaryBytes"]]]
    (let [out (str root "/" name ".wasm")
          r @(process ["node" "host/js/node_modules/wabt/bin/wat2wasm" "--enable-multi-memory"
                       (str "host/wasm/src/ppocr-" name ".wat") "-o" out]
                      {:inherit true :shutdown nil})]
      (assert (zero? (:exit r)) "WABT compile failed; install host/js dev dependencies")
      (str "export const " export " = Uint8Array.of(\n"
           (str/join ",\n" (map #(str "  " (str/join "," (map (fn [v] (bit-and v 255)) %)))
                                (partition-all 24 (seq (fs/read-all-bytes out))))) "\n);\n"))))
(def target "host/js/src/ppocr-link.js")
(def content (str "// Generated by bb tools/ppocr/wasm_link.clj from host/wasm/src/ppocr-*.wat.\n" (str/join "\n" parts)))
(when (not= content (when (fs/exists? target) (slurp target))) (spit target content))
