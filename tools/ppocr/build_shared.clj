#!/usr/bin/env bb
;; Build the qualified implementation once; no model or corpus downloads.
(require '[babashka.fs :as fs] '[babashka.process :refer [process shell]] '[clojure.string :as str])
(def env {"EMON_RS_PPOCR" "1" "EMON_CS_SHARED_COMPILATION" "false"})
(def r @(process ["kin/scripts/emon-rs-build"] {:extra-env env :out :string :err :inherit :shutdown nil}))
(assert (zero? (:exit r)) "reference build failed")
(def driver (str/trim (:out r)))
(def crate (str (fs/parent (fs/parent (fs/parent driver)))))
(fs/copy "tools/ppocr/hosts.rs" (str crate "/src/ppocr-hosts.rs") {:replace-existing true})
(spit (str crate "/Cargo.toml") "\n[[bin]]\nname = \"ppocr-hosts\"\npath = \"src/ppocr-hosts.rs\"\n" :append true)
(fs/copy "host/rust/src/ppocr_abi.rs" (str crate "/src/ppocr_abi.rs") {:replace-existing true})
(spit (str crate "/src/lib.rs") "\npub mod ppocr_abi;\n" :append true)
(spit (str crate "/Cargo.toml") (str/replace (slurp (str crate "/Cargo.toml")) "[lib]\n" "[lib]\ncrate-type = [\"rlib\", \"cdylib\"]\n"))
(fs/copy "host/rust/src/ppocr_tess_drop.rs" (str crate "/src/ppocr_tess_drop.rs") {:replace-existing true})
(spit (str crate "/src/tess.rs") "\ninclude!(\"ppocr_tess_drop.rs\");\n" :append true)
(def runtime (str (fs/absolutize ".cache/ppocr/onnxruntime-osx-arm64-1.22.0/lib")))
(def flags (str "-A warnings --cfg ppocr -L native=/opt/homebrew/lib -L native=" (fs/absolutize ".cache/ppocr") " -L native=" runtime " -C link-arg=-Wl,-rpath," runtime))
(shell {:dir crate :extra-env {"RUSTFLAGS" flags} :shutdown nil} "cargo" "build" "--offline" "--release" "--lib" "--bin" "ppocr-hosts" "--features" "tesseract,__test_hooks")
(def ext (if (= "Mac OS X" (System/getProperty "os.name")) "dylib" "so"))
(def dest (str ".cache/ppocr/libemon_ppocr_adapter." ext))
(fs/copy (str crate "/target/release/libemon." ext) dest {:replace-existing true})
(when (= ext "dylib") (shell {:shutdown nil} "install_name_tool" "-id" (str "@rpath/libemon_ppocr_adapter." ext) dest))
(when (= ext "dylib") (shell {:shutdown nil} "codesign" "--force" "--sign" "-" dest))
(println dest)
