#!/usr/bin/env bb
;; The Dart and Flutter packages of emon (K7, P13.20, D895; D884, D885, D886, D896).   bb dart
;;
;;   host/dart/emon_core              the core: ffigen bindings over emon.h, the API, the hook that fetches libemon and pdfium
;;   host/dart/emon_ocr_*             one package for each OCR adapter (tesseract, ppocr, vision, winocr; mlkit is a Flutter plugin)
;;   host/dart/emon                   the pure-Dart turnkey (core + the platform's default adapter, packs fetched on demand)
;;   host/dart/emon_flutter           the Flutter turnkey (emon + ML Kit on Android + a ChangeNotifier for pack downloads)
;;   host/dart/examples/...           a CLI example and the Flutter example app
;;
;;   bb dart --bindings [--check]     regenerate lib/src/bindings.g.dart from host/c/include/{emon,emon_adapter}.h with ffigen (--check: fail when it differs)
;;   bb dart --packs [--check]        regenerate lib/src/packs.g.dart from release/packs/packs.json (--check: fail when it differs)
;;   bb dart --sha-table FILE         write lib/src/native_assets.g.dart from the SHA256SUMS of a release (the archives `emon-c-<version>-<triple>.tar.gz`), at release time (D886)
;;   bb dart --stamp DIR              copy host/dart to DIR with `0.0.0-dev` replaced by version.edn's version (the published packages are the stamped copy)
;;   bb dart --analyze                `dart analyze` for every package
;;   bb dart --test                   `dart test` for every pure-Dart package (needs `EMON_NATIVE_DIR`: a directory with the C archive(s) of `bb package --host c`)
;;   bb dart --check                  the drift checks and --analyze
;;
;; NOT a gate by itself (the tests need a built C library: `bb package --host c`); `bb package --host dart --check` is the consumer check.
(require '[babashka.fs :as fs]
         '[babashka.process :as p]
         '[cheshire.core :as json]
         '[clojure.edn :as edn]
         '[clojure.string :as str])

(def args (vec *command-line-args*))
(defn flag? [f] (some #{f} args))
(defn opt [f] (second (drop-while #(not= f %) args)))
(defn die [& xs] (binding [*out* *err*] (println (str "FAIL " (apply str xs)))) (System/exit 1))
(defn say [& xs] (println (apply str xs)) (flush))

(def root (str (fs/canonicalize ".")))
(def dart-root (str root "/host/dart"))
(def version (:version (edn/read-string (slurp "version.edn"))))

(defn sh [{:keys [dir env]} & cmd]
  (let [r (apply p/shell (cond-> {:out :string :err :string :continue true} dir (assoc :dir (str dir)) env (assoc :extra-env env)) (map str cmd))]
    {:exit (:exit r) :out (str (:out r)) :err (str (:err r))}))

(defn sh! [opts & cmd]
  (let [r (apply sh opts cmd)]
    (when-not (zero? (:exit r)) (die (str/join " " (take 4 cmd)) " failed (exit " (:exit r) ")\n" (:out r) (:err r)))
    r))

(def packages
  "Every package directory, the pure-Dart ones first (`test?`: `dart test` runs there)."
  [{:dir "emon_core" :test? true}
   {:dir "emon_ocr_tesseract" :test? true}
   {:dir "emon_ocr_ppocr" :test? true}
   {:dir "emon_ocr_vision" :test? true}
   {:dir "emon_ocr_winocr" :test? true}
   {:dir "emon" :test? true}
   {:dir "emon_ocr_mlkit" :flutter? true}
   {:dir "emon_flutter" :flutter? true :test? true}])

;; ------------------------------------------------------------------------------------------------ the generated files

(defn dart-str [s] (str "'" (-> s (str/replace "\\" "\\\\") (str/replace "'" "\\'") (str/replace "$" "\\$")) "'"))
(defn dart-list [xs] (str "[" (str/join ", " (map dart-str xs)) "]"))

(defn packs-dart []
  (let [cat (json/parse-string (slurp "release/packs/packs.json") true)]
    (str "// GENERATED by `bb dart --packs` from release/packs/packs.json (release/packs/packs.edn, DEVLOG D885, D898). Do not edit.\n"
         "import 'packs.dart';\n\n"
         "/// The pack catalogue: what the C library verifies every pack against.\n"
         "const List<PackInfo> kPackCatalogue = [\n"
         (str/join ""
                   (for [pk (:packs cat)]
                     (str "  PackInfo(\n"
                          "    id: " (dart-str (:id pk)) ",\n"
                          "    rev: " (:rev pk) ",\n"
                          "    engine: " (dart-str (:engine pk)) ",\n"
                          "    kind: " (dart-str (:kind pk)) ",\n"
                          "    languages: " (dart-list (:langs pk)) ",\n"
                          "    scripts: " (dart-list (:scripts pk)) ",\n"
                          "    licence: " (dart-str (:licence pk)) ",\n"
                          "    files: [" (str/join ", " (for [f (:files pk)] (str "PackFile(" (dart-str (:name f)) ", " (dart-str (:sha256 f)) ", " (:bytes f) ")"))) "],\n"
                          "  ),\n")))
         "];\n")))

(defn write-or-check! [path content check?]
  (if check?
    (if (= content (when (fs/exists? path) (slurp path)))
      (say "ok   " path " is what it is generated from")
      (die path " is not what `bb dart " (if (str/includes? path "packs.g") "--packs" "--bindings") "` generates: run it and commit the result"))
    (do (spit path content) (say "wrote " path))))

(defn bindings! [check?]
  (let [pkg (str dart-root "/emon_core")
        out (if check? (str (fs/create-temp-dir {:prefix "emon-bindings-"}) "/bindings.g.dart") (str pkg "/lib/src/bindings.g.dart"))]
    (sh! {:dir pkg} "dart" "pub" "get")
    (sh! {:dir pkg} "dart" "run" "tool/ffigen.dart" out)
    (when check?
      (let [committed (str pkg "/lib/src/bindings.g.dart")]
        (if (= (slurp out) (slurp committed))
          (say "ok   " committed " is what ffigen generates from host/c/include")
          (die committed " is not what ffigen generates from host/c/include: run `bb dart --bindings` and commit the result"))))
    (when-not check? (say "wrote " out))))

;; The SHA-256 table the build hook verifies the downloaded archives against, from the release's SHA256SUMS. Written at release time (D886), never committed with real values.
(defn native-table-dart [sums-file]
  (let [rows (for [l (str/split-lines (slurp sums-file))
                   :let [[_ sha f] (re-matches #"([0-9a-f]{64})\s+\*?(?:.*/)?(emon-c-(\d[^/]*?)-([a-z0-9_]+(?:-[a-z0-9_]+)+)\.tar\.gz)" l)]
                   :when sha]
               (let [[_ _ file ver triple] (re-matches #"([0-9a-f]{64})\s+\*?(?:.*/)?(emon-c-(\d[^/]*?)-([a-z0-9_]+(?:-[a-z0-9_]+)+)\.tar\.gz)" l)]
                 {:triple triple :file file :sha sha :ver ver}))]
    (when (empty? rows) (die sums-file " lists no emon-c-<version>-<triple>.tar.gz archive"))
    (str "// GENERATED at release time by `bb dart --sha-table` from the release's SHA256SUMS (DEVLOG D886). Do not edit.\n"
         "import 'native_assets.dart';\n\n"
         "const NativeAssetTable kNativeAssets = NativeAssetTable(\n"
         "  version: " (dart-str (:ver (first rows))) ",\n"
         "  archives: {\n"
         (str/join "" (for [r (sort-by :triple rows)] (str "    " (dart-str (:triple r)) ": NativeArchive(" (dart-str (:file r)) ", " (dart-str (:sha r)) "),\n")))
         "  },\n);\n")))

;; ------------------------------------------------------------------------------------------------ analyze, test, stamp

(defn pkg-dir [p] (str dart-root "/" (:dir p)))
(defn existing [ps] (filter #(fs/exists? (str (pkg-dir %) "/pubspec.yaml")) ps))
(defn pub-tool [p] (if (:flutter? p) ["flutter"] ["dart"]))

(defn analyze! []
  (doseq [p (existing packages)]
    (let [d (pkg-dir p)
          _ (apply sh! {:dir d} (concat (pub-tool p) ["pub" "get"]))
          r (apply sh {:dir d} (concat (pub-tool p) ["analyze" "--fatal-infos"]))]
      (if (zero? (:exit r))
        (say "ok   dart analyze " (:dir p))
        (die "dart analyze " (:dir p) "\n" (:out r) (:err r))))))

(defn test! []
  (doseq [p (existing packages) :when (:test? p)]
    (let [d (pkg-dir p)]
      (when (fs/directory? (str d "/test"))
        (let [r (apply sh {:dir d :env (cond-> {} (System/getenv "EMON_NATIVE_DIR") (assoc "EMON_NATIVE_DIR" (System/getenv "EMON_NATIVE_DIR")))}
                       (concat (pub-tool p) ["test"]))]
          (if (zero? (:exit r)) (say "ok   dart test " (:dir p)) (die "dart test " (:dir p) "\n" (:out r) (:err r))))))))

(defn stamp! [dir]
  (fs/delete-tree dir)
  (fs/copy-tree dart-root dir)
  (doseq [f (file-seq (java.io.File. dir))
          :when (and (.isFile f) (re-find #"\.(yaml|dart|kt|gradle|md|podspec|swift)$" (.getName f)) (not (str/includes? (str f) "/.dart_tool/")) (not (str/includes? (str f) "/build/")))]
    (let [s (slurp f)]
      (when (str/includes? s "0.0.0-dev") (spit f (str/replace s "0.0.0-dev" version)))))
  (say "stamped " version " into " dir))

;; ------------------------------------------------------------------------------------------------ main

(cond
  (flag? "--bindings") (bindings! (flag? "--check"))
  (flag? "--packs") (write-or-check! (str dart-root "/emon_core/lib/src/packs.g.dart") (packs-dart) (flag? "--check"))
  (flag? "--sha-table") (let [f (opt "--sha-table")]
                          (spit (str dart-root "/emon_core/lib/src/native_assets.g.dart") (native-table-dart f))
                          (say "wrote host/dart/emon_core/lib/src/native_assets.g.dart"))
  (flag? "--stamp") (stamp! (or (opt "--stamp") (die "usage: bb dart --stamp DIR")))
  (flag? "--analyze") (analyze!)
  (flag? "--test") (test!)
  (flag? "--check") (do (bindings! true)
                        (write-or-check! (str dart-root "/emon_core/lib/src/packs.g.dart") (packs-dart) true)
                        (analyze!))
  :else (die "usage: bb dart --bindings | --packs | --sha-table FILE | --stamp DIR | --analyze | --test | --check   (see the header of tools/dart.clj)"))
