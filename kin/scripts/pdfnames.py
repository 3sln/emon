#!/usr/bin/env python3
"""Generate kin/pdfnames.kin: the PDF names emon's kin code compares against.

    python3 kin/scripts/pdfnames.py            write kin/pdfnames.kin
    python3 kin/scripts/pdfnames.py --check    fail if the committed file is stale

kin has no string values, so a source cannot write `(name-is x "Type")`. The
names are instead INTERNED at arena start-up, in this order, so a name's id is
its position here: `defenum pn` gives each a constant function (`(pn-type)`),
and `pn-chars`/`pn-span` are the bytes the arena interns. Append only: an id
is a position, and a golden file may mention one.
"""
import re, sys, os

NAMES = """
Type Length Filter DecodeParms F Predictor Colors BitsPerComponent Columns EarlyChange
FlateDecode Fl LZWDecode LZW ASCII85Decode A85 ASCIIHexDecode AHx RunLengthDecode RL
Crypt DCTDecode DCT JPXDecode CCITTFaxDecode CCF JBIG2Decode
Root Info Encrypt ID Size Prev XRefStm W Index N First Extends
Catalog Pages Page Kids Count Parent MediaBox CropBox Rotate Resources Contents
ObjStm XRef Linearized Version Lang MarkInfo Marked AcroForm StructTreeRoot
BleedBox TrimBox ArtBox UserUnit Names Outlines PageLabels Metadata Fields
Font XObject ExtGState ColorSpace Pattern Shading Properties ProcSet
Subtype Form Image Width Height
Title Author Subject Keywords Creator Producer CreationDate ModDate
BaseFont Encoding Differences BaseEncoding ToUnicode Widths FirstChar LastChar
FontDescriptor Flags MissingWidth Ascent Descent FontBBox FontMatrix
DescendantFonts DW DW2 CIDSystemInfo Ordering WMode
Type0 Type1 MMType1 TrueType Type3 CIDFontType0 CIDFontType2
WinAnsiEncoding MacRomanEncoding StandardEncoding MacExpertEncoding
Identity-H Identity-V
Matrix BBox MCID ActualText Alt E Artifact Pagination Layout Background Watermark Header Footer
DeviceGray DeviceRGB DeviceCMYK ca
""".split()

# Keywords the lexer recognises by id (0 is "any other keyword").
KEYWORDS = "true false null obj endobj stream endstream R xref trailer startxref f n".split()

def sym(n):
    s = re.sub(r'(?<=[a-z0-9])(?=[A-Z])', '-', n)
    s = re.sub(r'(?<=[A-Z])(?=[A-Z][a-z])', '-', s)
    return 'pn-' + s.lower()

def render():
    assert len(set(NAMES)) == len(NAMES), "duplicate name"
    syms = [sym(n) for n in NAMES]
    assert len(set(syms)) == len(syms), "duplicate symbol"
    chars, spans = [], []
    for n in NAMES:
        spans.append((len(chars), len(n)))
        chars.extend(ord(c) for c in n)
    out = [';; GENERATED by kin/scripts/pdfnames.py -- do not edit.',
           ';;',
           f';; The {len(NAMES)} PDF names emon\'s kin code compares by id (P1.4). The arena',
           ';; interns them, in this order, when it starts, so the id of a name is its',
           ';; position: `(pn-type)` answers the id of `/Type`. Appending a name is safe;',
           ';; nothing else is.',
           '(ns emon.pdfnames',
           '  (:require [emon.lang :refer [I32 Text defenum]]',
           '            [kin.lang :refer [defdata]]))',
           '',
           '(defenum ^:pub pn']
    rows = [f'  [{s} {i} "{n}"]' for i, (s, n) in enumerate(zip(syms, NAMES))]
    out.append('  [' + '\n   '.join(r.strip() for r in rows) + '])')
    out.append('')
    body = []
    for i in range(0, len(chars), 16):
        body.append(' '.join(str(c) for c in chars[i:i+16]))
    out += [';; the bytes of every name, back to back',
            '(defdata ^:pub pn-chars',
            '  :emitter kin.lang/flat-array',
            '  :data [' + '\n         '.join(body) + ']',
            '  :accessors {^I32 pn-chars-at [^I32 ignored ^I32 i]})',
            '']
    body = []
    flat = [x for s in spans for x in s]
    for i in range(0, len(flat), 16):
        body.append(' '.join(str(c) for c in flat[i:i+16]))
    out += [';; start offset into pn-chars, length',
            '(defdata ^:pub pn-span',
            '  :emitter kin.lang/flat-array',
            '  :stride 2',
            '  :data [' + '\n         '.join(body) + ']',
            '  :accessors {^I32 pn-span-count [^I32 ignored]',
            '              ^I32 pn-span-at [^I32 ignored ^I32 row ^I32 field]})',
            '']
    ksyms = ['pk-' + k.lower() for k in KEYWORDS]
    assert len(set(ksyms)) == len(ksyms)
    kchars, kspans = [], []
    for k in KEYWORDS:
        kspans.append((len(kchars), len(k)))
        kchars.extend(ord(c) for c in k)
    out += ['(defenum ^:pub pk',
            '  [' + '\n   '.join(f'[{s} {i + 1} "{k}"]' for i, (s, k) in enumerate(zip(ksyms, KEYWORDS))) + '])',
            '',
            ';; keyword bytes, back to back; row i is keyword id i + 1',
            '(defdata ^:pub pk-chars',
            '  :emitter kin.lang/flat-array',
            '  :data [' + ' '.join(str(c) for c in kchars) + ']',
            '  :accessors {^I32 pk-chars-at [^I32 ignored ^I32 i]})',
            '',
            ';; start offset into pk-chars, length',
            '(defdata ^:pub pk-span',
            '  :emitter kin.lang/flat-array',
            '  :stride 2',
            '  :data [' + ' '.join(str(x) for s in kspans for x in s) + ']',
            '  :accessors {^I32 pk-span-count [^I32 ignored]',
            '              ^I32 pk-span-at [^I32 ignored ^I32 row ^I32 field]})',
            '']
    return '\n'.join(out)

if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, '..', 'pdfnames.kin')
    text = render()
    if '--check' in sys.argv:
        if not os.path.exists(path) or open(path).read() != text:
            print('  FAIL kin/pdfnames.kin is stale; run python3 kin/scripts/pdfnames.py')
            sys.exit(1)
        print('  ok   kin/pdfnames.kin is current')
    else:
        open(path, 'w').write(text)
