;; The CJK radical fold: kin/radicals.kin and test/normalize/radicals.txt (DEVLOG P3.4, D136).
;;
;;     bb kin/scripts/radicals.clj            write them
;;     bb kin/scripts/radicals.clj --check    fail when the committed files are stale
;;
;; WHY. Chrome/Skia PDFs (and others) give CJK glyphs a ToUnicode of the KANGXI RADICALS (U+2F00..2FD5) and
;; CJK RADICALS SUPPLEMENT (U+2E80..2EF3) code points, characters meant to NAME a radical, where the text is the
;; unified ideograph the glyph draws (U+2F00 is drawn as U+4E00). NFC leaves them alone (a Kangxi radical's mapping
;; is a COMPATIBILITY one), so a search for the text misses it and a CER against the real text is wrong by the
;; whole of every such character. SPEC 3.6 folds them, at the text layer (`emon.normalize`, flag `nz-flag-radicals`).
;;
;; THE DATA, from the vendored UCD files of test/normalize/ (Unicode 18.0.0):
;;   * the 214 Kangxi radicals, and the CJK Radicals Supplement characters, that UnicodeData.txt gives a
;;     compatibility decomposition (`<compat> 4E00`): 214 and 2 (U+2E9F, U+2EF3);
;;   * the CJK Radicals Supplement characters that CJKRadicals.txt pairs with a unified ideograph "formed from
;;     that radical only" (29 of the block's 115: the rest, such as U+2E80 REPEAT, have no equivalent and stay);
;;   * the two agree where they overlap: every UnicodeData target IS CJKRadicals.txt's ideograph, or this script
;;     fails.
;; NOT FOLDED: the other supplement characters. NamesList.txt cross-references many of them to the character
;; they look like (`2EA0 CIVILIAN, x 6C11`), and Chrome's ToUnicode does give a few of those (U+2EA0, U+2EC4,
;; U+2ED1), but a cross-reference is "see also", not an equivalence, and some give two candidates: DEVLOG D136.
;; `kin/radicals.kin` is the table (`rad-fold`: [radical, ideograph] sorted by radical) and
;; `test/normalize/radicals.txt` its rows, from the same inputs, for the laws.
(ns radicals
  (:require [clojure.string :as str]))

(defn hexv [s] (Long/parseLong (str/trim s) 16))

(defn compat []
  (into (sorted-map)
        (for [l (str/split-lines (slurp "test/normalize/UnicodeData.txt"))
              :let [f (str/split l #";" -1)
                    cp (hexv (first f))
                    d (nth f 5)]
              :when (<= 0x2E80 cp 0x2FD5)
              :when (re-matches #"<compat> [0-9A-F]+" d)]
          [cp (hexv (second (str/split d #" ")))])))

(defn cjk-radicals []
  (into (sorted-map)
        (for [l (str/split-lines (slurp "test/normalize/CJKRadicals.txt"))
              :when (re-matches #"[0-9]+'*;.*" l)
              :let [[_ r u] (map str/trim (str/split l #";"))]
              :when (and (seq r) (seq u))]
          [(hexv r) (hexv u)])))

(defn table []
  (let [k (compat)
        c (cjk-radicals)
        kang-u (into (sorted-map) (filter (fn [[r _]] (<= 0x2F00 r 0x2FD5)) k))
        kang-c (into (sorted-map) (filter (fn [[r _]] (<= 0x2F00 r 0x2FD5)) c))
        supp-u (into (sorted-map) (filter (fn [[r _]] (<= 0x2E80 r 0x2EFF)) k))
        supp-c (into (sorted-map) (filter (fn [[r _]] (<= 0x2E80 r 0x2EFF)) c))]
    (assert (= 214 (count kang-u)) "214 Kangxi radicals in UnicodeData")
    (assert (= kang-u kang-c) "UnicodeData and CJKRadicals.txt agree on every Kangxi radical")
    (assert (= #{0x2E9F 0x2EF3} (set (keys supp-u))) "UnicodeData decomposes two supplement characters")
    (assert (every? (fn [[r u]] (or (not (contains? supp-c r)) (= u (get supp-c r)))) supp-u)
            "and agrees with CJKRadicals.txt where both speak")
    (assert (= 29 (count supp-c)) (str "29 supplement radicals have an equivalent in CJKRadicals.txt, found " (count supp-c)))
    (into (sorted-map) (concat kang-u supp-u supp-c))))

(defn render [t]
  (let [flat (mapcat (fn [[r u]] [r u]) t)]
    (str ";; GENERATED by kin/scripts/radicals.clj from test/normalize/UnicodeData.txt and CJKRadicals.txt -- do not edit.\n"
         ";;\n"
         ";; The CJK radical fold of `emon.normalize` (P3.4, D136): " (count t) " characters of the Kangxi Radicals block\n"
         ";; (U+2F00..2FD5) and the CJK Radicals Supplement block (U+2E80..2EF3), each with the unified ideograph it\n"
         ";; is drawn as, sorted by the radical.\n"
         "(ns emon.radicals\n"
         "  (:require [emon.lang :refer [I32]]\n"
         "            [kin.lang :refer [defdata]]))\n\n"
         ";; radical, unified ideograph\n"
         "(defdata ^:pub rad-fold\n"
         "  :emitter kin.lang/flat-array\n"
         "  :stride 2\n"
         "  :data [" (str/join "\n         " (map #(str/join " " %) (partition 2 flat))) "]\n"
         "  :accessors {^I32 rad-count [^I32 ignored]\n"
         "              ^I32 rad-at [^I32 ignored ^I32 row ^I32 field]})\n")))

(defn rows [t]
  (str "# GENERATED by kin/scripts/radicals.clj -- do not edit. Read by kin/normalizetest.kin (P3.4, D136).\n"
       "# radical <TAB> the unified ideograph it folds to (hex code points)\n"
       (str/join "\n" (map (fn [[r u]] (format "%04X\t%04X" r u)) t)) "\n"))

(defn -main [& args]
  (let [t (table)
        files {"kin/radicals.kin" (render t) "test/normalize/radicals.txt" (rows t)}]
    (if (some #{"--check"} args)
      (let [bad (remove (fn [[p s]] (and (.exists (java.io.File. ^String p)) (= s (slurp p)))) files)]
        (if (seq bad)
          (do (println "FAIL" (str/join ", " (map first bad)) "differ from what radicals.clj makes") (System/exit 1))
          (println "  ok   kin/radicals.kin and test/normalize/radicals.txt match the UCD files")))
      (doseq [[p s] files]
        (spit p s)
        (println "  wrote" p (count s) "bytes")))))

(apply -main *command-line-args*)
